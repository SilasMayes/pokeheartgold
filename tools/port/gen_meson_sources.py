#!/usr/bin/env python3
"""Writes src/meson.build: the explicit source lists for the port's meson build.

The list is what the DS build links: the src/ objects named in main.lsf (src/ also holds files
the ROM doesn't use, such as src/text_0205B4EC.c, a stale copy of dialog_box.c). Rerun after
adding, removing or renaming a file in main.lsf. CI runs it with --check to catch a stale list.

Groups:
  hgss_c          game C code, every target
  hgss_lobby_c    Wi-Fi Plaza lobby + GameSpy chat (C), desktop only like Platinum's ppwlobby
  hgss_lobby_cpp  the same, C++ part
Left out entirely:
  src/to91_msl_*.cpp  MSL C++ runtime pieces; the host C++ runtime has operator new/delete
  src/data/wifi_setup_data_*.c
                      tables of the Wi-Fi setup utility (src/wifi_setup/, below)
  src/data/middleware_*.c
                      version strings of the SDK libraries that libntr provides
  src/wifi_setup/     the DWC Wi-Fi setup utility (DWC_StartUtility in the real SDK), which
                      the Platinum port also skips: Wi-Fi settings belong to the port itself
"""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "src"

LOBBY_DIRS = ("lobby", "chat")
EXCLUDED_GLOBS = (
    "to91_msl_*.cpp",
    # tools/s2c.py output for code the port leaves out: the Wi-Fi setup utility's tables (see
    # src/wifi_setup/ below) and the version strings of the SDK libraries libntr replaces
    "data/wifi_setup_data_*.c",
    "data/middleware_*.c",
)
# Files under src/ that are not part of the build (port-specific files live in src/port/,
# which has its own list once it exists)
SKIP_DIRS = ("port", "wifi_setup")


def linked_sources():
    """src/ sources of the objects main.lsf links, in path order."""
    lsf = (ROOT / "main.lsf").read_text()
    paths = []
    for obj in sorted(set(re.findall(r"Object\s+(src/\S+)\.o\b", lsf))):
        for suffix in (".c", ".cpp"):
            path = ROOT / (obj + suffix)
            if path.exists():
                paths.append(path)
                break
        else:
            sys.exit(f"main.lsf links {obj}.o but there is no source for it")
    return paths


def collect():
    game, lobby_c, lobby_cpp = [], [], []
    excluded = {p for g in EXCLUDED_GLOBS for p in SRC.glob(g)}
    for path in linked_sources():
        if path in excluded:
            continue
        rel = path.relative_to(SRC)
        top = rel.parts[0] if len(rel.parts) > 1 else ""
        if top in SKIP_DIRS:
            continue
        if top in LOBBY_DIRS:
            (lobby_c if path.suffix == ".c" else lobby_cpp).append(rel.as_posix())
        elif path.suffix == ".c":
            game.append(rel.as_posix())
        else:
            sys.exit(f"unexpected C++ file outside the lobby: src/{rel}")
    return game, lobby_c, lobby_cpp


def render(game, lobby_c, lobby_cpp):
    def block(name, items):
        body = "".join(f"    '{i}',\n" for i in items)
        return f"{name} = files(\n{body})\n"

    return (
        "# Generated by tools/port/gen_meson_sources.py: rerun it after adding or removing files.\n"
        "# Port build only; the DS build (make) finds its sources itself.\n\n"
        + block("hgss_c", game)
        + "\n"
        + block("hgss_lobby_c", lobby_c)
        + "\n"
        + block("hgss_lobby_cpp", lobby_cpp)
    )


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if src/meson.build is stale")
    args = ap.parse_args()
    text = render(*collect())
    out = SRC / "meson.build"
    if args.check:
        if not out.exists() or out.read_text() != text:
            sys.exit("src/meson.build is stale: run tools/port/gen_meson_sources.py")
        return
    out.write_text(text)
    game, lc, lcpp = collect()
    print(f"src/meson.build: {len(game)} game C, {len(lc)} lobby C, {len(lcpp)} lobby C++")


if __name__ == "__main__":
    main()
